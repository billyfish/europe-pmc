package uk.ac.earlham.pmc;

/**
 * A single grant record as returned by the Europe PMC Grist API.
 */
public class GristResult {

	/** The grant's ID. */
	private String gr_id;

	/** The grant's title. */
	private String gr_title;

	/** The name of the grant's funder. */
	private String gr_funder;

	/** The institution that holds the grant. */
	private String gr_institution;
	
	
}
